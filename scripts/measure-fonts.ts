// Measures the bundled fonts' advance widths (in em) for printable ASCII so
// layout code and ECharts can size text the way the browser will render it.
// Run: node scripts/measure-fonts.ts > src/core/metrics.ts
import { readFileSync } from 'node:fs';
import { createRequire } from 'node:module';
import { chromium } from 'playwright';

const require = createRequire(import.meta.url);
const FONTS = [
  ['Inter', 'inter'],
  ['Source Serif 4', 'source-serif-4'],
  ['Nunito', 'nunito'],
  ['JetBrains Mono', 'jetbrains-mono'],
] as const;

const faces = FONTS.map(([family, pkg], i) => {
  const font = readFileSync(require.resolve(`@fontsource-variable/${pkg}/files/${pkg}-latin-wght-normal.woff2`)).toString('base64');
  return `@font-face{font-family:F${i};src:url(data:font/woff2;base64,${font}) format('woff2');font-weight:100 900}`;
});
const browser = await chromium.launch();
const page = await browser.newPage();
await page.setContent(`<style>${faces.join('')}</style>${FONTS.map((_, i) => `<span style="font-family:F${i}">x</span><span style="font-family:F${i};font-weight:600">x</span>`).join('')}`);
const widths = await page.evaluate(async (n) => {
  await document.fonts.ready;
  const ctx = document.createElement('canvas').getContext('2d')!;
  const out: number[][][] = [];
  for (let i = 0; i < n; i++) {
    out.push(
      [400, 600].map((weight) => {
        ctx.font = `${weight} 100px F${i}`;
        const row: number[] = [];
        for (let c = 32; c < 127; c++) row.push(Math.round(ctx.measureText(String.fromCharCode(c)).width) / 100);
        return row;
      }),
    );
  }
  return out;
}, FONTS.length);
await browser.close();
console.log(`// Generated by scripts/measure-fonts.ts. Advance widths in em for chars 32..126: [regular, semibold].
export const METRICS: Record<string, [number[], number[]]> = {
${FONTS.map(([family], i) => `  '${family}': [${JSON.stringify(widths[i]![0])}, ${JSON.stringify(widths[i]![1])}],`).join('\n')}
};`);
