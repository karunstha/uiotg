// Measures Inter's advance widths (in em) for printable ASCII so ECharts can lay
// out labels with the same metrics the browser will render with.
// Run: node scripts/measure-inter.ts > src/core/metrics.ts
import { readFileSync } from 'node:fs';
import { createRequire } from 'node:module';
import { chromium } from 'playwright';

const require = createRequire(import.meta.url);
const font = readFileSync(require.resolve('@fontsource-variable/inter/files/inter-latin-wght-normal.woff2')).toString('base64');
const browser = await chromium.launch();
const page = await browser.newPage();
await page.setContent(`<style>@font-face{font-family:M;src:url(data:font/woff2;base64,${font}) format('woff2');font-weight:100 900}</style><span style="font-family:M">x</span><span style="font-family:M;font-weight:600">x</span>`);
const widths = await page.evaluate(async () => {
  await document.fonts.ready;
  const ctx = document.createElement('canvas').getContext('2d')!;
  const out: Record<string, number[]> = {};
  for (const weight of [400, 600]) {
    ctx.font = `${weight} 100px M`;
    const row: number[] = [];
    for (let c = 32; c < 127; c++) row.push(Math.round(ctx.measureText(String.fromCharCode(c)).width) / 100);
    out[weight] = row;
  }
  return out;
});
await browser.close();
console.log(`// Generated by scripts/measure-inter.ts. Advance widths in em for chars 32..126.
export const INTER_REGULAR = ${JSON.stringify(widths[400])};
export const INTER_SEMIBOLD = ${JSON.stringify(widths[600])};`);
